/// 单实例守门：同一个状态目录，同一时刻只许一份桌面端在跑。
///
/// # 为什么必须有
///
/// 2026-08-21 实测的事故链：装机版与 dev 构建**同时运行**，共用
/// `%LOCALAPPDATA%\cortex` —— 两份进程各自持有同一把 refresh token 去轮换，
/// 服务端轮换是一次性作废旧值的，于是**后轮换的把先轮换的作废**：
/// 输家的每个请求 401，而客户端把 401 读成别的问题，一路连锁到
/// 「agent 被 1 秒一次地杀了 639+ 次」。settings.json 同理：两份进程
/// 互相覆盖对方存的 base_url，症状是「地址串台」。
///
/// 这不是「用户不该同时开两个」—— 窗口标题和图标一模一样，**用户根本
/// 看不出自己开了两个**。程序自己守门，才叫自身防护。
///
/// # 机制：文件排它锁，不是 PID 文件
///
/// PID 文件要处理陈旧（进程死了文件还在）、要防 PID 复用。排它锁
/// （Windows 的 LockFileEx）由内核持有，**进程一死（包括崩溃）自动释放**，
/// 没有陈旧问题可言。
///
/// # 已知空洞
///
/// 老版本（≤0.1.15）不抢这把锁，所以「老装机版已开 + 新 dev 版再开」拦得住
/// （新版抢不到锁就退出？不 —— 老版没锁，新版**能**抢到，两份照跑）。
/// 这个空洞要等装机版升到带锁的版本才闭合，拦不住的那段时间里
/// `just app-status` 的「哪个 exe」一栏是唯一的可见性。
