/// 跨重启记住的那几项**非密**设置 —— 现在只有 cortexd 地址。
///
/// # 为什么不放进凭据库
///
/// 地址不是秘密：它显示在设置页上、写在文档里、也印在错误信息里。
/// 把它塞进钥匙串会让「读设置」变成一次跨进程调用，还会在某些平台上
/// 弹授权框 —— 为一个不需要保护的值付这个代价没有道理。
///
/// # 为什么值得单独存
///
/// 在此之前 `AppConfig` 完全活在内存里：**重启之后地址回到编译期默认值**。
/// 一个把 cortexd 部署在别处的人，每次打开都要重填一遍地址 ——
/// 而他还没登录，所以连「登录状态记住了」都轮不到。
