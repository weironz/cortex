/// 「有东西等着你看」—— 应用**没有焦点**时把消息送到窗口外面去。
///
/// # 在补什么
///
/// 一轮跑完之后，应用内已经有两处提示（侧栏那个勾、底部那条提示条）。
/// 但它们都长在窗口里，而这个能力想省掉的事恰恰是「隔一会儿点进去看一眼」
/// —— 桌面端最小化、浏览器标签在后台时，那两处一处都看不到。
///
/// # 为什么不引通知插件
///
/// 一开始的判断是「要引三套原生通道 + 权限流程」，那是按「六个平台都要」
/// 算的。但这个产品**只发 Windows 安装包与 Web**（README「还不能做的」
/// 里写着 macOS / Linux 桌面产物要自己 `flutter build`）—— 于是只剩两条，
/// 而两条各自都有零依赖的走法：
///
/// * **Windows**：`FlashWindowEx`（user32）。任务栏按钮闪一下，这是
///   Windows 上「有东西等你」的标准信号，**不需要任何权限**。
///   仓库里已经在用 `dart:ffi` 调 user32（单实例守门），照那个模式抄。
/// * **Web**：`Notification`（`package:web` 已经是依赖）。要权限，
///   所以**第一次真的有东西要通知时才问** —— 开机就弹权限框的应用，
///   用户十次有九次点「拒绝」，然后这个能力就永久没了。
///
/// macOS / Linux 桌面上这一条是空操作，如实返回 `false`。**不假装成功** ——
/// 与 `copy_image` 那条同一纪律：静默当作做到了，是最难自查的一类 bug。
///
/// # 为什么是「闪一下」而不是弹一条系统通知
///
/// Windows 弹真正的 toast 要注册 AppUserModelID、要走 WinRT，
/// 而它买到的东西与闪任务栏是同一个：**让人知道该回来了**。
/// 代价差一个量级。等到有人真的要求「通知中心里留一条记录」再说。
