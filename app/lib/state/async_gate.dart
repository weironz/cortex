/// 异步门控约定 —— 界面「能不能点、为什么灰」从此只有一个形状。
///
/// # 为什么立这层纸
///
/// `state/` 下二十多个 controller 各自手搓 loading/error/data 三件套：
/// 一个布尔、一个 `String?`、一份数据，三者的搭配关系靠每个调用方自己
/// 记。质量回顾 2026-08-25 的根因 B 记的就是这个形状的账：页面级一个
/// `_busy` 串起十几个控件，任何一个在飞请求把不相干的控件一起变灰，而
/// 界面上没有任何「为什么灰」的说明；「已存密钥像空的」「默认值不可见」
/// 则是三态（未设 / 已设但不显示 / 正在改）写漏了一例。
///
/// 这份文件是收敛的形状约定，不是大重写计划。boy-scout：经过一处收一处。
///
/// # 形状一句话
///
/// - **加载 / 错误 / 数据用 `AsyncValue<T>` 一个类型表达**，不许再新写
///   `bool loading` + `String? error` 的裸字段对（Riverpod 自带，不需要
///   任何新依赖）。
/// - **界面上任何一个点不动的控件，旁边必须能找出原因文案**。
///   「禁用必有原因」—— 灰掉从来不是问题，说不出为什么灰才是。
///
/// # 什么时候**不**用 AsyncValue
///
/// 高频逐 token 更新的流式状态（`StreamingTurn` 那一层）继续用裸字段：
/// 它的纪律是 **identity 稳定**（每次增量都要 `==` 到旧值，否则 `select`
/// 全量重建），而 `AsyncData(value)` 每次包一层新对象恰恰破坏这一点。
/// 约定管的是**门**（请求-响应）这一侧，不是**流**这一侧。
///
/// # 迁移方式：读侧门先行
///
/// 存量状态的三裸字段不立刻动 —— 动存储真相会牵动所有读写方。第一步是在
/// **读的一侧**把三个字段折回一扇门（一个派生 `Provider<AsyncValue<T>>`），
/// 界面改走 `gate.when(...)`；等某个状态再也没有直接读裸字段的消费者，
/// 存储真相才换形状。第一个落地实例：会话列表，见
/// `chat_controller.dart` 末尾的 [sessionListGateProvider]。
///
/// # 密钥 / 默认值这类三态输入
///
/// 「未设 / 已设但不显示 / 正在改」是三态，空框只能表达第一态 —— 这就是
/// 「已存密钥像空的」的病理。共享控件 [SecretField]
/// （`widgets/secret_field.dart`）收编这三态，并把「禁用必有原因」做成
/// 构造期断言：`enabled: false` 不给 [SecretField.disabledReason] 直接
/// 抛。设置页再出现这类框，一律用它，不再各自手搓。
