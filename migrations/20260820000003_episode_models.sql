-- 每条 assistant 消息记下**它实际是谁写的**。
--
-- ══════════════════════════════════════════════════════════
--  为什么要存，而不是显示的时候现算
--
--  在此之前这个信息**从来没被存过**，而且是被主动丢掉的：
--  `cortex-agent/src/turn.rs` 里那行 `let (msg, _usage) = ...`
--  —— 模型名就在那个 `_usage` 里。
--
--  `cortex_auth.usage` 表确实有 `model` 一列，但它在账户库、
--  且没有任何字段挂得回某一条消息，重建不出「这句话是谁答的」。
--
--  # 「自动」档让这件事从锦上添花变成必须
--
--  自动档是**按请求**挑模型的（`resolve_auto` 跟着每次 `/llm/stream`
--  跑），而一轮对话有几次工具调用就发几次请求。也就是说同一条回复
--  可能先后经手好几个模型，而用户今天完全看不出这一句是谁答的。
--
--  # 为什么是数组而不是一列文本
--
--  正因为上面那条：一轮可能不止一个。存最后一个会把「先用便宜的跑
--  工具、再用贵的写答案」这件事整个抹掉。
--
--  **连续重复在写入时就去掉**（`cortex-agent` 那侧做）：一轮跑 20 次
--  工具调用、每次都是同一个模型时，存 20 份相同字符串既占地方，
--  画出来也是 `A → A → A …` 的噪音。只去**连续**的 ——
--  `A → B → A` 要原样留着，那是真的换回去了。
--
--  # NULL 是「不知道」，不是「没有模型」
--
--  迁移之前的历史消息、以及导入进来的 ChatGPT / Claude 记录，
--  这一列都是 NULL。界面据此**什么都不画** —— 猜一个「默认模型」
--  填上去等于对历史撒谎，而用户没有任何办法看出那是猜的。
-- ══════════════════════════════════════════════════════════

ALTER TABLE episodes ADD COLUMN models TEXT[];
