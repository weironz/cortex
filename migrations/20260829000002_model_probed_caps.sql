-- 供应商接口**当场说出来**的能力，最近一次「获取模型列表」问到的那份。
--
-- ══════════════════════════════════════════════════════════
--  这一列是快照，而 catalog 那份迁移说过快照不能存 —— 为什么这里可以
--
--  20260821000001 拒绝存富信息的理由是**价格**：目录更新之后老来源会一直
--  显示旧价，而「界面上写着一个早就不对的数字」比查不到更糟。
--
--  这一列不存价格，只存能力位（看不看得懂图、调不调得动工具）。两者的
--  过期代价完全不同：
--
--   * 价格错了 → 用户按一个错的数字做决定，而他没有办法发现；
--   * 能力位错了 → 要么被多拦一次（他能看见，且能手动覆盖掉），
--     要么放行之后供应商自己报错（也看得见）。
--
--  而且它的刷新时机是**用户自己点的那个按钮**，与 catalog 同一刻 ——
--  两者要么一起新、要么一起旧，不会出现「型号是新的、能力是旧的」。
--
--  # 为什么不干脆每次列来源时现问
--
--  列来源是打开设置页就发的请求。现问意味着每次打开都多几百毫秒到几秒
--  （Ollama 那条要逐个模型问），而这些位一年也变不了几次。
--
--  # 为什么与 caps_overrides 分开两列
--
--  一个是机器答的，一个是人答的，**优先级不同**（人 > 机器 > 目录 > 定义）。
--  混在一列里就分不出「这一位是他自己按的」——而界面上那个「你改的」
--  标记正依赖这个区分：分不出来的话，一次探测会让所有位都显示成用户改过的。
-- ══════════════════════════════════════════════════════════

ALTER TABLE model_sources
    ADD COLUMN probed_caps JSONB NOT NULL DEFAULT '{}'::jsonb;

ALTER TABLE model_sources
    ADD CONSTRAINT model_sources_probed_caps_is_object
    CHECK (jsonb_typeof(probed_caps) = 'object');

COMMENT ON COLUMN model_sources.probed_caps IS
    '最近一次拉列表时供应商接口自己报的能力，模型 id → 能力位。只有 OpenRouter / Ollama 说得出。';
