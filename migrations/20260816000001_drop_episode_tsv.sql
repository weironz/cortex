-- episodes.tsv 与它的 gin 索引：删掉。
--
-- ══════════════════════════════════════════════════════════
--  判据还是那一句：**这张列离开记忆能力还有没有意义**
--
--  `tsv` 的唯一消费者是 BM25 那一路召回，而召回整个留在了 Cormex ——
--  它连查询侧的分词器（`cortex_memory::tokenize`）都在那边，这个仓库
--  一行都没有。于是这一列在这里只有写入没有读取。
--
--  留着它的代价不是那点存储，是**一个假信号**：后来的人看见一列
--  TSVECTOR 加一个 gin 索引，会合理地认为「这儿有全文搜索」，然后
--  基于一列恒为空的数据去写查询 —— 那种错误不报错，只是搜不到东西。
--
--  写入侧同时删掉 `NewEpisode::tsv_source`。留着那个字段更糟：调用方
--  会认真地填一份分词结果进来，而它被写进一列没人读的数据里。
-- ══════════════════════════════════════════════════════════
--
-- ⚠️ 这一条同时废掉了 init 里【写入纪律】的第 4 条（「tsv 与主行同事务
-- 写入，永不异步补写」）。那条纪律本身没错，它只是**没有约束对象了**：
-- 这一侧不再有 tsv。真要在 Cormex 那边加回全文检索，纪律照旧成立，
-- 而那张表在那个仓库里。
--
-- 不改 init 那个文件是因为它已经在开发机的库上跑过，sqlx 会比对校验和 ——
-- 整个文件内容都进校验和，改一个字都会让已有的库拒绝迁移。

-- 先索引后列：反过来也能跑（DROP COLUMN 会连带删掉依赖它的索引），
-- 但那样这份 migration 就读不出「有一个索引被删掉了」这件事
DROP INDEX IF EXISTS idx_episodes_tsv;

ALTER TABLE episodes DROP COLUMN IF EXISTS tsv;
