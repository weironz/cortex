-- 智能体能用哪些工具。
--
-- ══════════════════════════════════════════════════════════
--  为什么是「关掉哪些」而不是「开着哪些」
--
--  存**禁用清单**（空 = 全开），而不是存启用清单（空 = 全关）。
--  两者对老数据的表现完全不同：
--
--  * 禁用清单：这一列加上去时所有已有的智能体都是空数组 → 全开 →
--    行为与加这一列之前**一模一样**。
--  * 启用清单：同样的空数组读成「一个工具都不给」→ 所有已有的智能体
--    当场变哑巴，而没有任何地方会报错。
--
--  加一列不该改变任何既有对象的行为，除非那正是这次改动的目的。
--
--  另一个好处在将来：新增一个内置工具时，禁用清单里没提到它，
--  于是它对所有智能体自动可用 —— 而启用清单要求逐个智能体去补一次，
--  漏掉的那些会静默地用不上新工具。
-- ══════════════════════════════════════════════════════════
--
-- ⚠️ 存的是**工具名**（`read_file` / `shell` / …），不是某种分类。
-- 分类（「文件类」「执行类」）会在加工具时要求有人去更新一张映射表，
-- 而那张表漏一行的症状是某个工具静默不受这个开关管。

ALTER TABLE assistants
    ADD COLUMN disabled_tools TEXT[] NOT NULL DEFAULT '{}';

COMMENT ON COLUMN assistants.disabled_tools IS
    '这个智能体**关掉**的工具名。空数组 = 全开（也是老数据的取值）。
     存禁用而非启用：加这一列不该改变任何已有智能体的行为。';
