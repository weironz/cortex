-- 默认模型：把角色指派给「哪条来源的哪个型号」。
--
-- ══════════════════════════════════════════════════════════
--  为什么要有这张表
--
--  在它之前，「用哪个模型」只有两个来源：部署的环境变量（`CORTEX_LLM_MODEL`
--  / `fast_model`），和用户**逐轮**的选择。中间那一层缺着 ——
--  「我这个账号平时默认用哪个」没有地方存。
--
--  逐轮选择替代不了它：那是「这一句用哪个」，关掉窗口就该忘。而
--  `ModelTier::Cheap`（后台抽取、会话命名那些杂活）**根本不经过用户**，
--  它今天只能用部署配的那个 —— 一个自带 key 的人没有任何办法让它走自己
--  的账户。
--
--  # 为什么是三个角色，不是四个
--
--  Cherry Studio 那一页有「翻译模型」。我们没有翻译功能 ——
--  摆一个没人调用的角色出来，就是又一次「造好了没人用」，
--  而用户会以为自己配的东西在起作用。
--
--  绘画那个是真的：`generate_image` 现在自己挑「最便宜的能生图的」，
--  指派之后按指派的来。
-- ══════════════════════════════════════════════════════════

CREATE TABLE model_roles (
    -- `main` / `cheap` / `image`。**不做外键也不做枚举**：
    -- 加一个角色时不必动 schema，而认不认得由代码说了算
    -- （认不出的角色读出来直接忽略，见 `model_roles.rs`）
    role       TEXT        PRIMARY KEY,
    -- 指向 `model_sources.id`，或字面量 `deployment`（部署提供那条）。
    --
    -- **不加外键。** 部署那条根本没有行 —— 它是环境变量配出来的，
    -- 外键会让「指派给部署提供」这件最常见的事写不进去。
    -- 来源被删之后这里留一条指向空的记录，读的时候回落并记 WARN；
    -- 那比让删除操作因为外键失败要好，见 `pick_source` 同一个判据。
    source_id  TEXT        NOT NULL,
    model      TEXT        NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT model_roles_model_not_blank CHECK (btrim(model) <> '')
);
