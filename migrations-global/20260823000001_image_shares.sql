-- 分享出去的图 —— **一条免登录就能打开的链接**。
--
-- ══════════════════════════════════════════════════════════
--  ⚠️ 为什么它在 `migrations-global/` 而不是 `migrations/`
-- ══════════════════════════════════════════════════════════
--
-- 分享链接按定义是给一个**没有凭据的人**看的：那条 GET 上没有
-- Authorization、没有 cookie、没有 ticket，什么都没有。于是服务端从请求里
-- 得不到任何「这是谁的图」的线索 —— 而租户是按 schema 分的
-- （见 `cortex-store` 的多租户说明）。
--
-- 把 token 存进租户自己的 schema 会怎样：公开那条路由拿到一个 token，
-- 却不知道该去哪个 schema 里查它。剩下的办法只有「挨个 schema 扫一遍」，
-- 那既慢又把「某个 schema 存在」变成可探测的信息。
--
-- 所以 token → (哪个租户, 哪张图) 这张映射必须是**全局**的。这与
-- `cortex_auth.users` 是同一类东西：跨租户唯一，整个部署只跑一遍。
--
-- ══════════════════════════════════════════════════════════
--  为什么 token 是随机的，而不是复用 blob hash
-- ══════════════════════════════════════════════════════════
--
-- blob hash 会出现在别的响应里（画廊、对话附件、导出的存档）。拿它当分享
-- 凭据，等于「凡是见过这张图的人都永久有权限」—— 而用户以为自己刚刚才
-- 把它分享出去。token 是一个**只在他点下分享那一刻才存在**的东西，
-- 撤销就是删掉这一行，链接当场 404。
CREATE TABLE cortex_auth.image_shares (
    -- 32 字节随机，hex 编码 = 64 字符。够长到不可枚举，
    -- 且十六进制在 URL 路径里不用担心任何转义
    token       TEXT        PRIMARY KEY CHECK (length(token) BETWEEN 20 AND 128),
    -- 这张图住在哪个租户的 schema 里。**不加外键** —— 跨 schema 引用不了，
    -- 而且这张表比任何一个租户都长命（租户注销时由那侧清理）
    schema_name TEXT        NOT NULL,
    image_id    TEXT        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    -- 同一张图只该有一条分享记录：重复点「分享」应当拿到**同一条链接**，
    -- 而不是每点一次多一条谁也撤不干净的 URL
    UNIQUE (schema_name, image_id)
);

-- 画廊要回答「这张分享了没有」，查的是 (schema, image)。UNIQUE 那个约束
-- 自带索引，正好就是它 —— 所以这里没有额外索引。
